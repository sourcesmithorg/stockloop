/**
 * Initial defaults for one country. Unknown/unmapped codes return the app's
 * existing defaults rather than a guess — an honest fallback beats a fabricated
 * match. Callers must show the returned values before submitting them.
 */
export function countryDefaults(country: string): { currency: string; timezone: string } {
  const entry = COUNTRY_DEFAULTS[country];
  if (!entry) return { currency: DEFAULT_CURRENCY, timezone: DEFAULT_TIMEZONE };
  return { currency: entry[0], timezone: entry[1] };
}
